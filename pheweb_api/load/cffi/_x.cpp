int make_matrix(const char *sites_filepath, const char *augmented_pheno_glob, const char *matrix_filepath) {
    BgzipWriter writer(matrix_filepath);

    LineReader sites_reader;
    sites_reader.attach(sites_filepath);

    std::vector<std::string> aug_filepaths = glob(augmented_pheno_glob);
    size_t N_phenos = aug_filepaths.size();
    std::cout << "N_phenos = " << N_phenos << std::endl;
    std::vector<LineReader> aug_readers(N_phenos);
    std::vector<std::string> aug_phenocodes(N_phenos);
    std::vector<unsigned> aug_n_per_assoc_fields(N_phenos); // initialized to 0s.
    // set_ulimit_num_files(N_phenos + 100); // are python files still open?
    for (size_t i = 0; i < N_phenos; i++) {
        aug_readers[i].attach(aug_filepaths[i]);
        aug_phenocodes[i] = aug_filepaths[i];
        size_t last_slash_idx = aug_phenocodes[i].find_last_of("/");
        if (std::string::npos != last_slash_idx) {
            aug_phenocodes[i].erase(0, last_slash_idx + 1);
        }
        if (endsWith(aug_phenocodes[i], ".gz")) {
            aug_phenocodes[i] = aug_phenocodes[i].erase(aug_phenocodes[i].length() - 3);
        }
    }

    // Headers:
    // sites.tsv's header must begin with "chrom pos ref alt ".
    // Every file's header must begin with the header of sites.tsv
    // All fields after the ones in sites.tsv will be written as "<field>@<pheno>"
    static const std::string cpra_header = "chrom\tpos\tref\talt\t";
    if(0 != sites_reader.line.compare(0, cpra_header.size(), cpra_header)) { throw std::runtime_error("[sites.tsv header doesn't begin with \"chrom\tpos\tref\talt\t\"]"); }
    for (size_t i=0; i < N_phenos; i++) {
        if(0 != aug_readers[i].line.compare(0, sites_reader.line.size(), sites_reader.line)) {
            std::ostringstream errstream;
            errstream << "[One of the pheno files has a header that doesn't begin with the header of sites.tsv (or it failed to read).]";
            errstream << "[bad phenocode = " << aug_phenocodes[i] << "]";
            errstream << "[bad pheno file = " << aug_filepaths[i] << "]";
            errstream << "[bad pheno header = " << aug_readers[i].line << "]";
            errstream << "[sites.tsv header = " << sites_reader.line << "]";
            throw std::runtime_error(errstream.str().c_str());
        }
    }
    writer.write("#"); // tabix needs the header commented.
    writer.write(sites_reader.line); // no trailing \t or \n
    for (size_t i=0; i < N_phenos; i++) {
        std::string per_assoc_fields = aug_readers[i].line.substr(sites_reader.line.size(), std::string::npos);
        std::istringstream line_stream(per_assoc_fields);
        std::string field;
        std::getline(line_stream, field, '\t'); // consume first tab.
        while(std::getline(line_stream, field, '\t')) {
            writer.write("\t");
            writer.write(field);
            writer.write("@");
            writer.write(aug_phenocodes[i]);
            aug_n_per_assoc_fields[i]++;
        }
    }
    writer.write("\n");
    const size_t n_per_variant_fields = n_fields(sites_reader.line);
    // advance every file to its 1st data-line
    sites_reader.next();
    for (size_t i=0; i<N_phenos; i++) aug_readers[i].next();

    // Data:
    // Every aug_pheno is a subsequence of sites.tsv.
    // If a line in an aug_pheno has the same chrom-pos-ref-alt as sites.tsv, then it must have the sites.tsv line as its prefix.
    //    (ie, it must have the same per-variant fields, in the same order.)
    // So, we iterate over sites.tsv, printing and advancing any aug_pheno that matches CPRA, and printing '' for every field in non-matching aug_phenos.
    while(1) {
        writer.write(sites_reader.line);

        size_t pos_after_cpra = pos_after_n_of_char(sites_reader.line, 4, '\t');

        for (size_t i=0; i<N_phenos; i++) {
            if (!aug_readers[i].eof() && 0 == sites_reader.line.compare(0, pos_after_cpra, aug_readers[i].line, 0, pos_after_cpra)) { // CPRAs match.
                if (0 != aug_readers[i].line.compare(0, sites_reader.line.size(), sites_reader.line)) {
                    std::ostringstream errstream;
                    errstream << "[There's a variant in a pheno file that has different information from that same variant in sites.tsv.]";
                    errstream << "[bad phenocode = " << aug_phenocodes[i] << "]";
                    errstream << "[bad pheno line = " << aug_readers[i].line << "]";
                    errstream << "[bad sites.tsv line = " << sites_reader.line << "]";
                    throw std::runtime_error(errstream.str().c_str());
                }
                if (n_fields(aug_readers[i].line) != n_per_variant_fields + aug_n_per_assoc_fields[i]) { // correct number of fields on line.
                    std::ostringstream errstream;
                    errstream << "[a pheno has a line with a different number of tab-delimited fields than its header]";
                    errstream << "[bad phenocode = " << aug_phenocodes[i] << "]";
                    errstream << "[bad pheno line = " << aug_readers[i].line << "]";
                    errstream << "[num fields on line = " << n_fields(aug_readers[i].line) << "]";
                    errstream << "[num fields in header = " << n_per_variant_fields + aug_n_per_assoc_fields[i] << "]";
                    throw std::runtime_error(errstream.str().c_str());
                }
                writer.write(aug_readers[i].line.c_str() + sites_reader.line.size(), aug_readers[i].line.size() - sites_reader.line.size()); //write per-assoc fields
                aug_readers[i].next();

            } else { // CPRAs don't match
                // write blanks for this pheno
                for (size_t j=0; j<aug_n_per_assoc_fields[i]; j++) writer.write("\t");
            }
        }
        writer.write("\n");

        if (sites_reader.eof()) break;
        sites_reader.next();
    }

    writer.close();

    return 0;
}



int filter_matrices_and_sites(const char *sites_filepaths_str,
                    const char *sites_tmp_filepaths_str,
                    const char *matrices_filepaths_str,
                    const char *matrices_tmp_filepaths_str,
                    const char *phenocodes_to_exclude_str)
{

    // ==== Setting up sites reader and writer ====

    // Parse "path1;path2;path3"
    std::vector<std::string> sites_filepaths;
    {
        std::stringstream ss(sites_filepaths_str);
        std::string filepath;

        while (std::getline(ss, filepath, ';')) {
            if (!filepath.empty())
                sites_filepaths.push_back(filepath);
        }
    }

    if (sites_filepaths.size() != 3)
        throw std::runtime_error("Expected exactly 3 site filepaths.");

    std::vector<std::string> sites_tmp_filepaths;
    {
        std::stringstream ss(sites_tmp_filepaths_str);
        std::string filepath;

        while (std::getline(ss, filepath, ';')) {
            if (!filepath.empty())
            sites_tmp_filepaths.push_back(filepath);
        }
    }

    std::vector<SiteFile> sitesFiles;

    for (int i = 0; i < sites_filepaths.size(); i++) {

        SiteFile site;

        site.filepath = sites_filepaths[i];
        // TODO: ensuring proper tmp filepath, could also pass in 
        site.tmp_filepath = sites_tmp_filepaths[i];
        
        site.reader = std::unique_ptr<LineReader>(new LineReader());
        site.reader->attach(site.filepath);

        site.writer = std::unique_ptr<BgzipWriter>(new BgzipWriter(site.tmp_filepath));

        // Writing header
        site.writer->write(site.reader->line);
        site.writer->write("\n");

        // Placing on first variant
        site.reader->next();

        sitesFiles.push_back(std::move(site));
    }


    // ==== Setting up phenocodes to exclude ====
    std::vector<std::string> phenocodes_to_exclude;
    {
        std::stringstream ss(phenocodes_to_exclude_str);
        std::string phenocode;

        while (std::getline(ss, phenocode, ';')) {
            if (!phenocode.empty())
                phenocodes_to_exclude.push_back(phenocode);
        }
    }

    // ==== Setting up matrices reader and writer ====

    // Parse "path1;path2;path3"
    std::vector<std::string> matrices_filepaths;
    {
        std::stringstream ss(matrices_filepaths_str);
        std::string filepath;

        while (std::getline(ss, filepath, ';')) {
            if (!filepath.empty())
                matrices_filepaths.push_back(filepath);
        }
    }

    std::vector<std::string> matrices_tmp_filepaths;
    {
        std::stringstream ss(matrices_tmp_filepaths_str);
        std::string filepath;

        while (std::getline(ss, filepath, ';')) {
            if (!filepath.empty())
            matrices_tmp_filepaths.push_back(filepath);
        }
    }

    if (matrices_filepaths.size() != matrices_tmp_filepaths.size())
    throw std::runtime_error("Number of matrix filepaths don't match number of tmp matrix files.");


    std::vector<Matrix> matrices;
    for (int i = 0; i < matrices_filepaths.size(); i++) {

        Matrix matrix;

        matrix.filepath = matrices_filepaths[i];
        matrix.tmp_filepath = matrices_tmp_filepaths[i];

        // attach reader and writer
        matrix.reader = std::unique_ptr<LineReader>(new LineReader());
        matrix.reader->attach(matrix.filepath);

        matrix.writer = std::unique_ptr<BgzipWriter>(new BgzipWriter(matrix.tmp_filepath));
        // filtering header and gathering idx to keep
        //matrix.reader->next();
        std::string header = matrix.reader->line;

        std::vector<std::string> fields_to_keep;

        std::stringstream ss(header);

        std::string column;
        int idx = 0;

        while (std::getline(ss, column, '\t')) {

            bool exclude = false;

            for (const auto& pheno : phenocodes_to_exclude) {
                if (column.find(pheno) != std::string::npos) {
                    exclude = true;
                    break;
                }
            }

            if (exclude)
                matrix.idx_to_exclude.push_back(idx);
            else
                fields_to_keep.push_back(column);

            idx++;
        }


        std::string new_header;

        for (size_t i = 0; i < fields_to_keep.size(); i++) {

            if (i)
                new_header += "\t";

            new_header += fields_to_keep[i];
        }


        matrix.writer->write(new_header);
        matrix.writer->write("\n");


        matrix.reader->next();
        matrix.current_line = matrix.reader->line;

        matrices.push_back(std::move(matrix));
    }

    size_t active_matrices = matrices.size();
    std::unordered_map<std::string, int> order_list = get_chrom_order_list();

    // Iterating through sites
    while (!sitesFiles[0].reader->eof()) {

        int empty_counter = 0;

        Variant siteVariant = lineToVariant(sitesFiles[0].reader->line, order_list);

        for (Matrix &matrix : matrices) {

            if (!matrix.keep_reading)
                continue;
            
            // Fetching variant
            while (true) {
                
                // Comparing site and matrix variant
                
                Variant matrixVariant = lineToVariant(matrix.reader->line, order_list);

                int cmp = which_variant_is_bigger(
                    siteVariant,
                    matrixVariant);
                
                // Found same site
                if (cmp == 0) {

                    // TODO:  removeMatrixFields & matrixVariantIsEmpty can be combined in one function
                    // std::pair<std::string, bool> removeMatrixFieldsAndCheckEmpty


                    matrix.current_line = removeMatrixFields(matrix.reader->line, matrix.idx_to_exclude);

                    matrix.write_variant = true;
                    // If matrix line is empty for every matrix, it will be discarded
                    if (matrixVariantIsEmpty(matrix.current_line))
                        empty_counter++;
                    break;
                }
                // If sites is further than matrix, fetch next variant in matrix
                if (cmp == 1) {
                    matrix.reader->next();

                    if (matrix.reader->eof()) {
                        matrix.keep_reading = false;
                        active_matrices--;
                        break;
                    }
                }
                // If matrix is further than site, skip until sites arrives at same position
                else {
                    matrix.write_variant = false;
                    empty_counter++;
                    break;
                }
            }
        }

        // IF site is present in some matrices
        if (empty_counter != active_matrices) {

            // writing back to sites
            for(SiteFile &siteFile : sitesFiles){
                siteFile.writer->write(siteFile.reader->line);
                siteFile.writer->write("\n");
            }

            // 
            for (Matrix &matrix : matrices) {

                if (!matrix.keep_reading || !matrix.write_variant){
                    continue;
                }

                matrix.writer->write(matrix.current_line);
                matrix.writer->write("\n");

                matrix.reader->next();

                if (matrix.reader->eof()) {
                    matrix.keep_reading = false;
                    active_matrices--;
                }
            }
        }

        // Advancing sites
        for(SiteFile &siteFile : sitesFiles){
            siteFile.reader->next();
        }
    }


    for(SiteFile &siteFile : sitesFiles){
            siteFile.writer->close();
        } 

    
    for (Matrix &matrix : matrices) {
        matrix.writer->close();
    }

    return 0;
}


